import { useEffect } from 'react';
import { useComponent4Selection } from '../../context/Component4SelectionContext';

export default function SelectionBar({ className = '' }) {
  const {
    district,
    year,
    month,
    districts,
    districtsLoading,
    districtsError,
    months,
    years,
    setDistrict,
    setYear,
    setMonth,
    confirmSelection,
  } = useComponent4Selection();

  // Forecast is the only place selectors appear; visiting it confirms the shared selection.
  useEffect(() => {
    confirmSelection();
  }, [confirmSelection]);

  const selectClass =
    'w-full rounded-xl border border-slate-200 bg-white px-3 py-2.5 text-base text-primary outline-none focus:border-secondary';

  return (
    <div
      className={`rounded-2xl border border-slate-100 bg-white p-4 shadow-sm md:p-5 ${className}`}
    >
      <div className="mb-3 flex flex-wrap items-end justify-between gap-2">
        <div>
          <p className="text-sm font-semibold uppercase tracking-wide text-secondary">
            Decision selection
          </p>
          <p className="mt-1 text-base text-slate-600">
            Choose district, year and month here. Other pages use this selection
            automatically. H1, H3 and H6 are generated by the backend.
          </p>
        </div>
      </div>

      {districtsError && (
        <p className="mb-3 text-sm text-danger">{districtsError}</p>
      )}

      <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        <label className="block">
          <span className="mb-1.5 block text-sm font-semibold text-slate-600">
            District
          </span>
          <select
            className={selectClass}
            value={district}
            disabled={districtsLoading || !districts.length}
            onChange={(e) => setDistrict(e.target.value)}
          >
            {(districts.length ? districts : [district]).map((name) => (
              <option key={name} value={name}>
                {name}
              </option>
            ))}
          </select>
        </label>

        <label className="block">
          <span className="mb-1.5 block text-sm font-semibold text-slate-600">
            Year
          </span>
          <select
            className={selectClass}
            value={year}
            onChange={(e) => setYear(e.target.value)}
          >
            {years.map((y) => (
              <option key={y} value={y}>
                {y}
              </option>
            ))}
          </select>
        </label>

        <label className="block">
          <span className="mb-1.5 block text-sm font-semibold text-slate-600">
            Month
          </span>
          <select
            className={selectClass}
            value={month}
            onChange={(e) => setMonth(e.target.value)}
          >
            {months.map((m) => (
              <option key={m.value} value={m.value}>
                {m.label}
              </option>
            ))}
          </select>
        </label>
      </div>
    </div>
  );
}
